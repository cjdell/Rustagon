impl<'a> Canvas<'a> {
  /// Draw `text` at `(x, y)` in `color`, scaled by `scale` (1 = 5x7 pixels
  /// per glyph). `\n` moves to the next line; non-ASCII characters render
  /// as `?`.
  pub fn draw_text(&mut self, text: &str, x: i32, y: i32, color: Rgb565, scale: u8) {
    let scale = scale.max(1) as i32;
    let mut cx = x;
    let mut cy = y;
    for ch in text.chars() {
      if ch == '\n' {
        cx = x;
        cy += LINE_HEIGHT as i32 * scale;
        continue;
      }
      let glyph = match ch {
        ' '..='~' => (ch as u8 - b' ') as usize,
        _ => (b'?' - b' ') as usize,
      };
      let base = glyph * GLYPH_W;
      for col in 0..GLYPH_W {
        let line = FONT_5X7[base + col];
        for row in 0..GLYPH_H {
          if line & (1 << row) != 0 {
            self.fill_rect(Rect::new(cx + col as i32 * scale, cy + row as i32 * scale, scale, scale), color);
          }
        }
      }
      cx += GLYPH_ADVANCE as i32 * scale;
    }
  }
}

/// Width in pixels of `text` at `scale` (maximum over lines, including
/// trailing spaces).
pub fn text_width(text: &str, scale: u8) -> i32 {
  let scale = scale.max(1) as i32;
  let mut max_w = 0i32;
  let mut cur = 0i32;
  for ch in text.chars() {
    if ch == '\n' {
      max_w = max_w.max(cur);
      cur = 0;
    } else {
      cur += GLYPH_ADVANCE as i32 * scale;
    }
  }
  max_w.max(cur)
}

/// Height in pixels of `text` at `scale` (number of lines incl. trailing
/// empty line for a trailing `\n`).
pub fn text_height(text: &str, scale: u8) -> i32 {
  let scale = scale.max(1) as i32;
  let lines = text.chars().filter(|&c| c == '\n').count() as i32 + 1;
  lines * LINE_HEIGHT as i32 * scale
}
