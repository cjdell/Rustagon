//! 5x7 bitmap font and text rendering on a [`Canvas`].
//!
//! Glyph data is the classic public-domain "font5x7" table used by
//! Adafruit-GFX: 5 columns per glyph, 7 rows, one byte per column with the
//! least-significant bit as the top row. Only printable ASCII (32-126) is
//! included; anything else renders as `?`.

use super::canvas::{Canvas, Rect, Rgb565};

/// Glyph width in pixels (at scale 1).
pub const GLYPH_W: usize = 5;
/// Glyph height in pixels (at scale 1).
pub const GLYPH_H: usize = 7;
/// Horizontal advance per character, including the 1px gap (at scale 1).
pub const GLYPH_ADVANCE: usize = 6;
/// Line height including the 1px gap below each line (at scale 1).
pub const LINE_HEIGHT: usize = 8;

